"""Export to the IMAS pulse_schedule IDS (target format 1).

imas-python is imported lazily inside the functions, so the rest of the package
works without IMAS.

Mapping (decision D12): the Ip node is looked up in the LOADED DD: DD 4
(4.0.0, 4.1.1 checked with imas-python 2.3.0) has ``flux_control/ip``, DD 3
(3.42.0) has ``flux_control/i_plasma``; the one that exists is filled. The DD
version is chosen by the caller (CLI ``--dd-version``), else globals.dd_version,
else DEFAULT_DD_VERSION = 4.0.0 (the version PDS uses).

* ``flux_control/ip/reference`` on ``flux_control/time`` and ``pulse_schedule/time``:
  the waveform vertices plus the segment boundaries (sampled linearly), IMAS sign
  kept (ITER Ip < 0, whatever the YAML convention), A and s;
  ``flux_control/ip/reference_name`` = designer name;
* absolute times (time bases, event time_stamp) are shifted by the design's
  ``time_offset_s`` (default 0: t = 0 at the plasma initiation, D10);
* segment boundaries as ``pulse_schedule/event(:)`` [PROPOSAL]: one event per
  segment, ``type/name`` = "pcs_segment", ``identifier`` = "segment:<id>:<name>",
  ``time_stamp`` = segment start, ``duration`` = segment duration.

Every field is checked against the loaded DD at run time; a field absent from
that DD version is skipped with a warning.
"""

from __future__ import annotations

import warnings
from pathlib import Path

import numpy as np

from .cut import cut_note
from .model import PulseDesign

DEFAULT_DD_VERSION = "4.0.0"
#: Ip node names in pulse_schedule/flux_control, newest first.
IP_NODE_NAMES = ("ip", "i_plasma")
EVENT_TYPE_NAME = "pcs_segment"
EVENT_TYPE_DESCRIPTION = (
    "Start of a PCS pulse-schedule segment [proposal, ip_waveform_export]"
)


def _node(ids, relpath: str):
    """Return the node at ``relpath`` ('a/b/c') or None (with a warning) if absent."""
    node = ids
    for part in relpath.split("/"):
        try:
            node = getattr(node, part)
        except AttributeError:
            warnings.warn(
                f"pulse_schedule/{relpath}: not in this DD version, skipped",
                stacklevel=3,
            )
            return None
    return node


def _set(ids_or_struct, relpath: str, value) -> bool:
    parent_path, _, leaf = relpath.rpartition("/")
    parent = _node(ids_or_struct, parent_path) if parent_path else ids_or_struct
    if parent is None:
        return False
    if not hasattr(parent, leaf):
        warnings.warn(f"{relpath}: not in this DD version, skipped", stacklevel=2)
        return False
    setattr(parent, leaf, value)
    return True


def ip_node_name(ps) -> str:
    """Name of the Ip node that exists in the loaded DD ("ip" in DD 4, "i_plasma" in DD 3)."""
    for name in IP_NODE_NAMES:
        if hasattr(ps.flux_control, name):
            return name
    raise AttributeError(
        f"pulse_schedule/flux_control has none of {IP_NODE_NAMES} in this DD version"
    )


def time_base(design: PulseDesign) -> np.ndarray:
    """Waveform vertices plus segment boundaries, sorted, duplicates merged."""
    t = np.concatenate([design.waveform.time, [s.start for s in design.segments]])
    t = np.unique(np.round(t, 12))
    return t


def resolve_dd_version(design: PulseDesign, dd_version: str | None = None) -> str:
    return str(dd_version or design.globals.get("dd_version") or DEFAULT_DD_VERSION)


def build_ids(design: PulseDesign, dd_version: str | None = None):
    import imas  # lazy: only this exporter needs IMAS

    dd_version = resolve_dd_version(design, dd_version)
    ps = imas.IDSFactory(version=dd_version).pulse_schedule()
    ps.ids_properties.homogeneous_time = 0
    ps.ids_properties.comment = (
        f"{design.name}: Ip reference with segment structure, generated by ip_waveform_export "
        f"(segments as event(:) = proposal; t = 0 at {design.time_origin}, "
        f"time_offset_s = {design.time_offset_s:g}). {design.globals.get('comment', '')}"
    ).strip()
    if (
        design.cut_at is not None
    ):  # D20: record the PSC clock offset (IDS times stay absolute)
        ps.ids_properties.comment = (
            f"{ps.ids_properties.comment} {cut_note(design)}; "
            f"psc_clock_offset_s = {design.cut_at + design.time_offset_s:.6f}"
        )
    t_design = time_base(design)
    ip = design.waveform.sample(t_design)
    t = t_design + design.time_offset_s
    ps.time = t
    base = f"flux_control/{ip_node_name(ps)}"
    if _set(ps, "flux_control/time", t):
        _set(ps, f"{base}/reference", ip)
        _set(ps, f"{base}/reference_name", design.waveform.designer_name)

    if _node(ps, "event") is not None:
        ps.event.resize(len(design.segments))
        for ev, seg in zip(ps.event, design.segments):
            _set(ev, "type/name", EVENT_TYPE_NAME)
            _set(ev, "type/description", EVENT_TYPE_DESCRIPTION)
            _set(ev, "identifier", f"segment:{seg.id}:{seg.name}")
            _set(ev, "time_stamp", float(seg.start + design.time_offset_s))
            _set(ev, "duration", float(seg.duration))
    return ps


def write_pulse_schedule_ids(
    design: PulseDesign, out_dir: str | Path, dd_version: str | None = None
) -> str:
    """Write the IDS to an HDF5 IMAS entry in ``out_dir``; returns the URI."""
    import imas
    import imas.util

    ps = build_ids(design, dd_version)
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    uri = f"imas:hdf5?path={out_dir}"
    with imas.DBEntry(
        uri, "w", dd_version=imas.util.get_data_dictionary_version(ps)
    ) as entry:
        entry.put(ps)
    return uri


def read_back(uri: str) -> dict:
    """Read the IDS written by ``write_pulse_schedule_ids`` into plain Python data."""
    import imas
    import imas.util

    with imas.DBEntry(uri, "r") as entry:
        ps = entry.get("pulse_schedule", autoconvert=False)
        dd = imas.util.get_data_dictionary_version(ps)
        node = ip_node_name(ps)
        fc = getattr(ps.flux_control, node)
        events = [
            (
                str(e.identifier),
                float(e.time_stamp),
                float(e.duration),
                str(e.type.name),
            )
            for e in ps.event
        ]
        return {
            "dd_version": dd,
            "ip_node": node,
            "time": np.array(ps.time),
            "flux_control_time": np.array(ps.flux_control.time),
            "ip": np.array(fc.reference),
            "events": events,
        }
