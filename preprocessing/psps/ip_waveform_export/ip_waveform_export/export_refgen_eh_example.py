"""PROPOSAL / ILLUSTRATIVE: the Ip reference modified by the PSC (decision D9 example).

In addition to the nominal RefGen schedule, this exporter writes

(a) ``<name>_refgen_eh.xml``: the nominal schedule plus exception segments
    taken from the PROPOSED ``exceptions:`` block of the input YAML:

    * SOFT exception (e.g. id 20 "ip_reduce_on_heating_loss"): one
      ``SIGNAL_TRAJECTORY Ipl_ref`` whose POINTs are a SCALE FACTOR (1.0 ->
      ``scale`` over ``transition_s``), applied on top of the running nominal
      trajectory by the behaviour-tree action ``typeAddition='silence,scale'``.
      Pattern: pcssp@2233365 (branch PSC-FWHL)
      ``generic/psc/Tests/assets/PS_FWHLEH.xml`` l.184-201 (segment 20,
      FUNCTION code / ``silence,offset``) and the RefGen composition rule
      ``Value = base .* scale + offset`` in
      ``generic/psc/+REFGEN/+MODEL/SignalGenClass.m`` l.411-439 (same commit);
    * HARD exception termination (e.g. id 41 "ip_termination"): ``Ipl_ref``
      ramps to 0 over ``ramp_to_zero_s``, modelled on FWHL segments 41/51
      (EHTerm1/EHTerm2) with ``typeAddition='replace'``;

(b) ``<name>_btree_eh.xml``: a Groot behaviour tree modelled on pcs@bb29ad6
    (add-AM) ``BTreeNominalWaveforms.xml`` plus the priority structure of
    ``BTreeFWHL.xml`` (PSC-FWHL): a reactive Fallback with
    [1] sudden hard exceptions (AssignValue of the hard segment id),
    [2] nominal segments in Parallel with the soft-exception overlay,
    [3] the list of hard-exception segments.

CAVEATS (also in README): the trigger ``heating_loss`` is a HYPOTHETICAL
blackboard signal (physically Ip is driven by the CS/PF circuits; the story is
"operating point changed after the loss of a heating source -> Ip target scaled
down as a precaution"); TC01 declares ``glb_ps__ip_too_high`` (pcs@add-AM
PSC_config/PSCGlobalMonConfig.xml:17-19) but no behaviour tree consumes it; the
termination ramp starts from the nominal maximum |Ip| (a real termination would
start from the current reference value). Not run through MATLAB/RefGen.
"""

from __future__ import annotations

import re
import xml.etree.ElementTree as ET
from dataclasses import dataclass
from pathlib import Path

from .export_refgen_xml import (
    IMAS_TO_PCS_IP_SIGN,
    build_tree,
    fmt_attr,
    fmt_float,
)
from .model import MAX_SEGMENT_ID, STOP_NAME, PulseDesign, ValidationError

PROPOSAL = "PROPOSAL / ILLUSTRATIVE"
#: STOP self-loop watchdog of pcs@add-AM BTreeNominalWaveforms.xml (SubTreeNominalStop).
STOP_WD_TIME = 5.0
#: Rule set of the FWHL exception trajectories (PS_FWHLEH.xml).
EH_RULES = (("ENTRY_RULE", "None"), ("EXIT_RULE", "Last"), ("EXECUTION_RULE", "Linear"))
SOFT_TYPE_ADDITIONS = ("silence,scale", "freeze,scale")
BT_HEADER = (
    f"{PROPOSAL}: Ip reference modified by the PSC (decision D9 example)",
    "generated by ip_waveform_export (option refgen-eh-example); segments in <name>_refgen_eh.xml",
    "modelled on pcs@bb29ad6 BTreeNominalWaveforms.xml + pcssp@2233365 BTreeFWHL.xml",
    "[1] sudden hard EH  [2] nominal segments || soft-EH overlay  [3] hard-EH list",
    "heating_loss = HYPOTHETICAL blackboard signal (not defined in any PCS config)",
    "glb_ps__ip_too_high: declared by TC01 (PSCGlobalMonConfig.xml:17-19), consumed nowhere",
)


@dataclass(frozen=True)
class SoftEH:
    name: str
    id: int
    trigger: str
    release: str
    scale: float
    transition_s: float
    wd_time: float
    wd_target: str
    type_addition: str = "silence,scale"


@dataclass(frozen=True)
class HardEH:
    name: str
    id: int
    ramp_to_zero_s: float
    sudden_trigger: str | None = None
    wd_target: str = STOP_NAME


def camel(name: str) -> str:
    return "".join(
        w[:1].upper() + w[1:].lower() for w in re.split(r"[^0-9A-Za-z]+", name) if w
    )


def parse_exceptions(design: PulseDesign) -> tuple[list[SoftEH], list[HardEH]]:
    raw = design.exceptions
    if not raw:
        raise ValidationError(
            [
                "the input has no 'exceptions:' block (see examples/ip_105073_like_with_exceptions.yaml)"
            ]
        )
    p: list[str] = []
    soft: list[SoftEH] = []
    hard: list[HardEH] = []
    try:
        for s in raw.get("soft") or []:
            soft.append(
                SoftEH(
                    name=str(s["name"]),
                    id=int(s["id"]),
                    trigger=str(s["trigger"]),
                    release=str(s["release"]),
                    scale=float(s["scale"]),
                    transition_s=float(s["transition_s"]),
                    wd_time=float(s["wd_time"]),
                    wd_target=str(s["wd_target"]),
                    type_addition=str(s.get("type_addition", "silence,scale")),
                )
            )
        for h in raw.get("hard") or []:
            hard.append(
                HardEH(
                    name=str(h["name"]),
                    id=int(h["id"]),
                    ramp_to_zero_s=float(h["ramp_to_zero_s"]),
                    sudden_trigger=None
                    if h.get("sudden_trigger") is None
                    else str(h["sudden_trigger"]),
                    wd_target=str(h.get("wd_target", STOP_NAME)),
                )
            )
    except (KeyError, TypeError, ValueError) as e:
        raise ValidationError([f"exceptions: malformed entry ({e!r})"]) from e

    nominal_ids = {s.id for s in design.segments}
    names = [s.name for s in design.segments] + [e.name for e in (*soft, *hard)]
    ids = [e.id for e in (*soft, *hard)]
    if len(set(names)) != len(names):
        p.append(f"exceptions: segment names not unique: {names}")
    if len(set(ids)) != len(ids) or nominal_ids & set(ids):
        p.append(
            f"exceptions: ids {ids} must be unique and differ from the nominal ids"
        )
    if any(not 0 <= i <= MAX_SEGMENT_ID for i in ids):
        p.append(f"exceptions: ids outside 0..{MAX_SEGMENT_ID}")
    hard_names = {h.name for h in hard}
    for s in soft:
        if s.type_addition not in SOFT_TYPE_ADDITIONS:
            p.append(f"{s.name}: type_addition must be one of {SOFT_TYPE_ADDITIONS}")
        if not s.scale > 0 or not 0 < s.transition_s <= s.wd_time:
            p.append(f"{s.name}: need scale > 0 and 0 < transition_s <= wd_time")
        if s.wd_target not in hard_names:
            p.append(f"{s.name}: wd_target {s.wd_target!r} must name a hard exception")
    for h in hard:
        if not h.ramp_to_zero_s > 0:
            p.append(f"{h.name}: ramp_to_zero_s must be > 0")
        if h.wd_target != STOP_NAME:
            p.append(f"{h.name}: wd_target must be {STOP_NAME!r}")
    if not soft or not hard:
        p.append("exceptions: at least one soft and one hard exception expected")
    if p:
        raise ValidationError(p)
    return soft, hard


def _trajectory(parent: ET.Element, signal: str, points) -> None:
    trajs = ET.SubElement(parent, "SIGNAL_TRAJECTORIES")
    traj = ET.SubElement(trajs, "SIGNAL_TRAJECTORY", {"name": signal})
    for tag, rule in EH_RULES:
        ET.SubElement(traj, tag, {"is": rule})
    ref = ET.SubElement(traj, "REFERENCE")
    for t, v in points:
        ET.SubElement(ref, "POINT", {"time": fmt_float(t), "value": fmt_float(v)})


def build_eh_schedule(design: PulseDesign) -> ET.ElementTree:
    soft, hard = parse_exceptions(design)
    tree = build_tree(design)
    root = tree.getroot()
    root.set("comment", f"{PROPOSAL}: {root.get('comment')}; plus exception segments")
    root.insert(
        0,
        ET.Comment(
            f" {PROPOSAL}: nominal schedule plus exception segments (decision D9 example). "
            "Triggers are hypothetical; not run through MATLAB parsePSXML/RefGen. "
        ),
    )
    sig = design.waveform.signal_name
    segs = root.find("SEGMENTS")
    for s in soft:
        segs.append(
            ET.Comment(
                f" {PROPOSAL} SOFT exception: Ipl_ref SCALE factor 1 -> {s.scale:g} over "
                f"{s.transition_s:g} s, applied on the running nominal trajectory by "
                f"typeAddition='{s.type_addition}' (pattern PS_FWHLEH.xml l.184-201) "
            )
        )
        el = ET.SubElement(
            segs,
            "SEGMENT",
            {
                "name": s.name,
                "id": str(s.id),
                "wd_time": fmt_attr(s.wd_time),
                "wd_target": s.wd_target,
            },
        )
        _trajectory(el, sig, [(0.0, 1.0), (s.transition_s, s.scale)])
    ip_pcs_max = float(max(IMAS_TO_PCS_IP_SIGN * design.waveform.value))
    for h in hard:
        segs.append(
            ET.Comment(
                f" {PROPOSAL} HARD exception termination: Ipl_ref from the nominal maximum "
                f"to 0 over {h.ramp_to_zero_s:g} s (pattern FWHL segments 41/51) "
            )
        )
        el = ET.SubElement(
            segs,
            "SEGMENT",
            {
                "name": h.name,
                "id": str(h.id),
                "wd_time": fmt_attr(h.ramp_to_zero_s),
                "wd_target": h.wd_target,
            },
        )
        _trajectory(el, sig, [(0.0, ip_pcs_max), (h.ramp_to_zero_s, 0.0)])
    ET.indent(root, space="  ")
    return tree


def _action(
    parent,
    name,
    signal,
    seg_id,
    type_addition,
    wd_time,
    wd_target,
    entry=None,
    condition=None,
):
    attrs = {"ID": "RefGen", "name": name, "signal": signal, "segmentID": str(seg_id)}
    if entry:
        attrs["entryRule"] = entry
    attrs["typeAddition"] = type_addition
    if condition:
        attrs["condition"] = condition
    attrs["wd_time"] = fmt_attr(wd_time)
    attrs["wd_target"] = str(wd_target)
    return ET.SubElement(parent, "Action", attrs)


def build_btree(design: PulseDesign) -> ET.Element:
    soft, hard = parse_exceptions(design)
    by_name = {s.name: s for s in design.segments}
    ids = {**{s.name: s.id for s in design.segments}, **{h.name: h.id for h in hard}}
    sig = design.waveform.signal_name

    root = ET.Element("root", {"main_tree_to_execute": "BehaviorTree"})
    for line in BT_HEADER:
        root.append(ET.Comment(f" {line} ".replace("--", "- -")))
    main = ET.SubElement(root, "BehaviorTree", {"ID": "BehaviorTree"})
    top = ET.SubElement(main, "Fallback", {"name": "FallbackNomEH", "Reactive": "1"})

    # [1] sudden hard exceptions: jump to the hard segment
    sudden = ET.SubElement(
        top, "Fallback", {"name": "FallHrdEHListSudden", "Reactive": "1"}
    )
    for h in hard:
        if not h.sudden_trigger:
            continue
        pre = ET.SubElement(
            sudden,
            "Precondition",
            {"name": f"{camel(h.name)}HrdEHSudden", "condition": h.sudden_trigger},
        )
        seq = ET.SubElement(ET.SubElement(pre, "ForceFailure"), "Sequence")
        ET.SubElement(
            seq,
            "Action",
            {
                "ID": "AssignValue",
                "source": "{current_segment}",
                "target": "{old_current_segment}",
            },
        )
        ET.SubElement(
            seq,
            "Action",
            {
                "ID": "AssignValue",
                "name": f"Assign{camel(h.name)}",
                "source": str(h.id),
                "target": "{current_segment}",
            },
        )

    # [2] nominal segments in parallel with the soft-exception overlay
    par = ET.SubElement(
        top, "Parallel", {"name": "ParSegNom", "threshold": "1", "mainTask": "1"}
    )
    nom = ET.SubElement(par, "Fallback", {"name": "FallNomSegList", "Reactive": "1"})
    for s in design.segments:
        pre = ET.SubElement(
            nom,
            "Precondition",
            {
                "name": f"Precond{camel(s.name)}",
                "condition": f"{{current_segment}} == {s.id}",
            },
        )
        ET.SubElement(pre, "SubTree", {"ID": f"SubTreeSeg{camel(s.name)}"})
    sft = ET.SubElement(
        par, "Parallel", {"name": "ParSftEHList", "threshold": "1", "mainTask": "-1"}
    )
    for s in soft:
        pre = ET.SubElement(
            sft,
            "Precondition",
            {"name": f"{camel(s.name)}SftEH", "condition": s.trigger},
        )
        ET.SubElement(pre, "SubTree", {"ID": f"SubTree{camel(s.name)}"})

    # [3] hard-exception segments
    hrd = ET.SubElement(top, "Fallback", {"name": "FallHrdEHList", "Reactive": "1"})
    for h in hard:
        pre = ET.SubElement(
            hrd,
            "Precondition",
            {
                "name": f"{camel(h.name)}HrdEH",
                "condition": f"{{current_segment}} == {h.id}",
            },
        )
        ET.SubElement(pre, "SubTree", {"ID": f"SubTree{camel(h.name)}"})

    # subtrees
    subtree_ids = []
    for s in design.segments:
        sid = f"SubTreeSeg{camel(s.name)}"
        subtree_ids.append(sid)
        bt = ET.SubElement(root, "BehaviorTree", {"ID": sid, "segmentID": str(s.id)})
        if s.is_stop:  # self-loop as in pcs@add-AM SubTreeNominalStop
            _action(
                bt,
                f"PathSeg{camel(s.name)}",
                "all",
                s.id,
                "replace",
                STOP_WD_TIME,
                s.id,
            )
        else:
            _action(
                bt,
                f"PathSeg{camel(s.name)}",
                "all",
                s.id,
                "replace",
                s.duration,
                by_name[s.wd_target].id,
            )
    for s in soft:
        sid = f"SubTree{camel(s.name)}"
        subtree_ids.append(sid)
        bt = ET.SubElement(root, "BehaviorTree", {"ID": sid, "segmentID": str(s.id)})
        _action(
            bt,
            f"Path{camel(s.name)}",
            sig,
            s.id,
            s.type_addition,
            s.wd_time,
            ids[s.wd_target],
            entry="Linear",
            condition=s.release,
        )
    for h in hard:
        sid = f"SubTree{camel(h.name)}"
        subtree_ids.append(sid)
        bt = ET.SubElement(root, "BehaviorTree", {"ID": sid, "segmentID": str(h.id)})
        _action(
            bt,
            f"Path{camel(h.name)}",
            "all",
            h.id,
            "replace",
            h.ramp_to_zero_s,
            ids[h.wd_target],
            entry="Linear",
        )

    model = ET.SubElement(root, "TreeNodesModel")
    assign = ET.SubElement(model, "Action", {"ID": "AssignValue"})
    ET.SubElement(assign, "input_port", {"name": "source"})
    ET.SubElement(assign, "input_port", {"name": "target"})
    for sid in subtree_ids:
        ET.SubElement(model, "SubTree", {"ID": sid})
    ET.indent(root, space="    ")
    return root


def write_eh_example(design: PulseDesign, out_dir: str | Path) -> tuple[Path, Path]:
    out_dir = Path(out_dir)
    xml_path = out_dir / f"{design.name}_refgen_eh.xml"
    bt_path = out_dir / f"{design.name}_btree_eh.xml"
    data = ET.tostring(
        build_eh_schedule(design).getroot(), encoding="ISO-8859-1", xml_declaration=True
    )
    xml_path.write_bytes(data + b"\n")
    bt = ET.tostring(build_btree(design), encoding="unicode")
    bt_path.write_text('<?xml version="1.0"?>\n' + bt + "\n", encoding="utf-8")
    return xml_path, bt_path
