"""Export to the PCSSP PSC RefGen XML schedule (target format 2).

Reference format: pcs@bb29ad6 (branch add-AM)
``top-models/magnetic-control/CREATE_TC_01/PSC_config/PS_NominalWaveforms.xml``
(copy in ``reference/``); reading rules: pcssp-nightly@ebf3ee0
``src/psc/+REFGEN/+MODEL/parsePSXML.m`` (copy in ``reference/``).

Mapping:

* ``DECLARATIONS/PARAMETERS``: one PARAMETER is always written because
  parsePSXML.m defines ``ListParams`` only when a PARAMETERS block exists and
  passes it on to every segment (no PARAMETERS -> undefined variable).
* ``DECLARATIONS/OUTPUTS/SIGNAL``: attribute set copied from the reference
  ``Ipl_ref`` declaration (name, signal_type, type, dimension, comment, value).
* ``SEGMENTS/SEGMENT name id wd_time wd_target``: wd_time = segment duration,
  wd_target = name of the next segment; the STOP segment has name and id only
  and no trajectory, as in the reference.
* per timed segment one ``SIGNAL_TRAJECTORY name=<signal>`` with
  ``EXECUTION_RULE is="Linear"``, ``ENTRY_RULE is="Step"``, ``EXIT_RULE is="last"``
  (the only values used by the 32 trajectories of the reference) and
  ``REFERENCE/POINT time value`` with segment-relative times: the waveform is
  cut at both segment boundaries, so every segment starts at its own t = 0.

SIGN RULE: the model and the IDS keep the IMAS sign (ITER Ip < 0). The PCS
reference Ipl_ref is positive (reference values 3.03e6 .. 4.03e6), so the value
is multiplied by IMAS_TO_PCS_IP_SIGN = -1 HERE and nowhere else; for ITER the
PCS frame therefore equals -Ip, the value the Session Leader edits (D11). The
PARAMETER ``ImasToPcsIpSign = -1`` documents the relation IDS -> PCS.

TIME: POINT times are segment-relative, so ``time_offset_s`` does not change
them; the absolute times in the comments are on the designer time origin.
"""

from __future__ import annotations

import xml.etree.ElementTree as ET
from pathlib import Path

from .cut import cut_note
from .model import PulseDesign, segment_points

IMAS_TO_PCS_IP_SIGN = -1.0

XSI_NS = "http://www.w3.org/2001/XMLSchema-instance"
SCHEMA_LOCATION = "http://www.ipp.mpg.de/2016/Schema/Schedule.xsd"

#: Declarations copied from the reference PS_NominalWaveforms.xml (OUTPUTS).
KNOWN_DECLARATIONS = {
    "Ipl_ref": {
        "signal_type": "Amplitude",
        "type": "double",
        "dimension": "1",
        "comment": "Nominal Ipl_ref waveform",
        "value": "0",
    },
}

TRAJECTORY_RULES = (
    ("EXECUTION_RULE", "Linear"),
    ("ENTRY_RULE", "Step"),
    ("EXIT_RULE", "last"),
)


def fmt_float(x: float) -> str:
    """Shortest round-trip repr, as in the reference ("0.0", "3033875.0")."""
    return repr(float(x) + 0.0)  # + 0.0 turns -0.0 (sign flip of 0) into 0.0


def fmt_attr(x: float) -> str:
    """wd_time style of the reference: integral values without decimals ("10")."""
    x = (
        round(float(x), 9) + 0.0
    )  # drop float noise of differences (e.g. a cut duration)
    return str(int(x)) if x.is_integer() else repr(x)


def build_tree(design: PulseDesign) -> ET.ElementTree:
    wf = design.waveform
    sig = wf.signal_name
    decl = KNOWN_DECLARATIONS.get(sig)
    if decl is None:
        raise KeyError(f"no declaration known for PCS signal {sig!r}")

    ET.register_namespace("xsi", XSI_NS)
    root = ET.Element(
        "SCHEDULE",
        {
            f"{{{XSI_NS}}}schemaLocation": SCHEMA_LOCATION,
            "name": f"{design.name} schedule",
            "comment": (
                f"Generated by ip_waveform_export from {wf.ids_path} "
                f"(IMAS sign, DD {design.globals.get('dd_version', '?')}); "
                f"{sig} = ImasToPcsIpSign x Ip_IMAS = -Ip (positive PCS frame); "
                f"t = 0 at {design.time_origin}"
                + (f"; {cut_note(design)}" if design.cut_at is not None else "")
            ),
        },
    )
    if design.cut_at is not None:
        root.insert(0, ET.Comment(f" {cut_note(design)} "))
    decls = ET.SubElement(root, "DECLARATIONS")
    params = ET.SubElement(decls, "PARAMETERS")
    params.append(
        ET.Comment(
            " parsePSXML.m needs a PARAMETERS block; this one documents the sign "
            "relation IDS -> PCS: Ipl_ref = ImasToPcsIpSign x Ip_IMAS "
        )
    )
    ET.SubElement(
        params,
        "PARAMETER",
        {
            "name": "ImasToPcsIpSign",
            "type": "double",
            "value": fmt_attr(IMAS_TO_PCS_IP_SIGN),
        },
    )
    outputs = ET.SubElement(decls, "OUTPUTS")
    ET.SubElement(outputs, "SIGNAL", {"name": sig, **decl})

    segs_el = ET.SubElement(root, "SEGMENTS")
    for seg in design.segments:
        if seg.is_stop:
            ET.SubElement(segs_el, "SEGMENT", {"name": seg.name, "id": str(seg.id)})
            continue
        segs_el.append(
            ET.Comment(
                f" {seg.name}: absolute {fmt_float(seg.start)} s to {fmt_float(seg.end)} s "
            )
        )
        seg_el = ET.SubElement(
            segs_el,
            "SEGMENT",
            {
                "name": seg.name,
                "id": str(seg.id),
                "wd_time": fmt_attr(seg.duration),
                "wd_target": seg.wd_target or "",
            },
        )
        trajs = ET.SubElement(seg_el, "SIGNAL_TRAJECTORIES")
        traj = ET.SubElement(trajs, "SIGNAL_TRAJECTORY", {"name": sig})
        for tag, rule in TRAJECTORY_RULES:
            ET.SubElement(traj, tag, {"is": rule})
        ref = ET.SubElement(traj, "REFERENCE")
        t_rel, vals = segment_points(wf, seg)
        for tr, val in zip(t_rel, vals):
            ET.SubElement(
                ref,
                "POINT",
                {"time": fmt_float(tr), "value": fmt_float(IMAS_TO_PCS_IP_SIGN * val)},
            )
    ET.indent(root, space="  ")
    return ET.ElementTree(root)


def write_refgen_xml(design: PulseDesign, out_path: str | Path) -> Path:
    out_path = Path(out_path)
    data = ET.tostring(
        build_tree(design).getroot(), encoding="ISO-8859-1", xml_declaration=True
    )
    out_path.write_bytes(data + b"\n")
    return out_path
