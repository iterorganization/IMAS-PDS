"""PSC-5: derive the four run variants A-D from examples/ip_105073_psc.yaml and write the
converter outputs (four PSC mask files, cut at the window start 84.317598 s, D20) into
<repo>/cases/input/psc/<variant>/.

  A_nom   nominal designer waveform (Ip reference of cases/input/psc/A_nom/ip_105073_psc_A_nom.yaml,
          the P2d nominal; or the optional third argument), D17 events as
          in the example (ip_too_high 15.25 MA, end_of_flux 8.0 kA, z_excursion 2 cm / 1 cm)
  B_edit  the example unchanged (+3 % edit, same events)
  C_zhold +3 % edit, ip_too_high disabled (threshold 20 MA), z_excursion 2 cm with release at
          1.5 cm (the P2e nominal run itself stays > 1 cm from 0.261 m during 84.5-86.27 s, so a
          1 cm release could not be met), end_of_flux 8.0 kA (never reached in P2e)
  D_eof   nominal waveform, end_of_flux threshold 8.30 kA (P2e-A NICE CS3L headroom 8.35 kA at
          84.3186 s, first < 8.30 kA at 84.396 s; 8.0 kA is never reached in P2e), eof
          ramp-down watchdog 2.0 s (instead of 3.0 s, so the escalation to segment 42 falls
          inside the 87 s window), z_excursion disabled (threshold 1 m) to isolate the case
usage: python make_psc_variants.py <repo root> <venv python> [<nominal designer yaml>]
"""

import copy
import subprocess
import sys
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
CONV = HERE.parent / "ip_waveform_export"
clone, py = Path(sys.argv[1]), sys.argv[2]
NOMINAL = Path(sys.argv[3]) if len(sys.argv) > 3 else clone / "cases/input/psc/A_nom/ip_105073_psc_A_nom.yaml"
base = yaml.safe_load((CONV / "examples/ip_105073_psc.yaml").read_text())
nominal = yaml.safe_load(NOMINAL.read_text())
REF = "pulse_schedule/flux_control/ip/reference"


def soft(d, name):
    return next(s for s in d["exception_handling"]["soft"] if s["name"] == name)


V = {}
d = copy.deepcopy(base); d["references"][REF] = copy.deepcopy(nominal["references"][REF])
d["globals"]["name"] = "ip_105073_psc_A_nom"; V["A_nom"] = d
d = copy.deepcopy(base); d["globals"]["name"] = "ip_105073_psc_B_edit"; V["B_edit"] = d
d = copy.deepcopy(base); d["globals"]["name"] = "ip_105073_psc_C_zhold"
d["events"]["ip_too_high"]["threshold"] = 20.0e6
d["events"]["ip_too_high"]["description"] = "DISABLED for run C (threshold 20 MA)"
d["events"]["z_excursion"]["release_threshold"] = 0.015
V["C_zhold"] = d
d = copy.deepcopy(base); d["references"][REF] = copy.deepcopy(nominal["references"][REF])
d["globals"]["name"] = "ip_105073_psc_D_eof"
d["events"]["end_of_flux"]["threshold"] = 8.30e3
d["events"]["end_of_flux"]["description"] = "run D: CS headroom below 8.30 kA (fires ~84.40 s in P2e-A)"
d["events"]["z_excursion"]["threshold"] = 1.0
d["events"]["z_excursion"]["release_threshold"] = 0.5
d["events"]["z_excursion"]["description"] = "DISABLED for run D (threshold 1 m)"
soft(d, "eof_rampdown")["wd_time"] = 2.0
V["D_eof"] = d

for name, d in V.items():
    out = clone / "cases/input/psc" / name
    out.mkdir(parents=True, exist_ok=True)
    y = out / f"{d['globals']['name']}.yaml"
    y.write_text("# generated by preprocessing/psps/psc_run/make_psc_variants.py (PSC-5)\n" + yaml.safe_dump(d, sort_keys=False))
    r = subprocess.run([py, "-I", str(CONV / "ip_waveform_export.py"), "--yaml", str(y), "--out-dir", str(out),
                        "--cut-at", "84.317598", "--psc-config", "--refgen"], capture_output=True, text=True)
    print(name, "rc", r.returncode, (r.stdout + r.stderr).strip().splitlines()[-3:])
    if r.returncode:
        sys.exit(r.returncode)
